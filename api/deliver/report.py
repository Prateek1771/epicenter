"""An incident as a Markdown file (GET /incidents/{id}/export.md): `human` for people (incident_info.md), `agent` for
coding agents (Claude Code, Codex, Cursor: an AGENTS-style context file). Pure: IncidentOut in, text out; no LLM, so
the same incident always gives the same file."""

from api.models import IncidentOut

FLAVORS = ("human", "agent")


def _svc(op: str) -> str:
    return op.split("/", 1)[0]


def _ruled_out(inc: IncidentOut) -> list[str]:
    return [
        f"- `{h.target}`: {h.status}" + (f" (score {h.score:.2f})" if h.score is not None else "")
        for h in inc.hypotheses
        if h.status in ("refuted", "pruned")
    ]


def _facts(inc: IncidentOut) -> list[str]:
    out = [
        f"- **Environment:** `{inc.env}`",
        f"- **Status:** {inc.status}",
        f"- **Alert on:** `{inc.symptom}`",
        f"- **Alerts joined:** {inc.alert_count}",
        f"- **Diagnosis run:** {inc.run}",
        f"- **Weights:** `{inc.weights_version}`",
    ]
    if inc.gaps:
        out.append(f"- **Couldn't see:** {', '.join(inc.gaps)} (those sources were down during the window)")
    return out


def _verdict(inc: IncidentOut) -> list[str]:
    v = inc.verdict
    if v is None:
        return [inc.no_root_cause.summary if inc.no_root_cause else "No verdict yet: the incident isn't diagnosed."]
    out = [f"- **Root cause:** `{v.root_cause.target}`, confidence {v.confidence:.0%}"]
    if v.owner:
        out.append(f"- **Owner:** {v.owner}")
    if v.change:
        out.append(
            f"- **Change:** {v.change.summary or v.change.id} on `{v.change.service}`"
            f" at {v.change.ts:%Y-%m-%d %H:%M:%S} UTC"
        )
    if v.footprint:
        out.append(f"- **Footprint:** {v.footprint.summary}")
    if v.second_root_cause:
        out.append(f"- **Second cause:** `{v.second_root_cause.target}`")
    if v.runner_up:
        out.append(f"- **Runner-up:** `{v.runner_up.target}`")
    if v.found_in_ms is not None:
        out.append(f"- **Found in:** {v.found_in_ms / 1000:.1f} s")
    out.append(f"- **Path (cause → symptom):** {' → '.join(f'`{p}`' for p in reversed(v.path))}")
    return out


def _evidence(inc: IncidentOut) -> list[str]:
    if not inc.verdict:
        return []
    return [f"- {e.id} · {e.kind} · {e.verdict}: {e.summary}" for e in inc.verdict.evidence]


def _actions(inc: IncidentOut) -> list[str]:
    return [
        f"{a.rank}. {a.name} ({a.chosen_by}" + (f"; fixed {', '.join(a.precedent)}" if a.precedent else "") + ")"
        for a in inc.actions
    ]


def human(inc: IncidentOut) -> str:
    lines = [f"# Incident {inc.id}", "", *_facts(inc), "", "## Verdict", "", *_verdict(inc)]
    if ev := _evidence(inc):
        lines += ["", "## Evidence", "", *ev]
    if ro := _ruled_out(inc):
        lines += ["", "## Ruled out", "", *ro]
    if inc.explanation and inc.explanation.claims:
        src = "AI explanation" if inc.explanation.source == "llm" else "built from the evidence (AI unavailable)"
        lines += ["", f"## Why ({src})", "", *[f"- {c.text} [{', '.join(c.cites)}]" for c in inc.explanation.claims]]
    if inc.actions:
        lines += ["", "## Proposed actions", "", *_actions(inc)]
    if inc.similar:
        lines += [
            "",
            "## Seen before",
            "",
            *[
                f"- {s.incident} (similarity {s.score:.2f}): cause `{s.cause}`; fixed by {', '.join(s.fixes) or '—'}"
                for s in inc.similar
            ],
        ]
    if inc.delivery:
        lines += [
            "",
            "## Delivered",
            "",
            *[f"- {k}: {'ok' if d.get('ok') else 'failed'}" for k, d in sorted(inc.delivery.items())],
        ]
    return "\n".join(lines) + "\n"


def agent(inc: IncidentOut) -> str:
    """For a coding agent opened on the failing service's repo: where to look, what's established, what not to do."""
    v = inc.verdict
    ops = sorted(set(v.path)) if v else []
    services = sorted({_svc(o) for o in ops})
    names = [f"`{o.split('/', 1)[1]}`" for o in ops if "/" in o]
    lines = [
        f"# Incident context: {inc.id}",
        "",
        "> Generated by Epicenter from its incident graph. Facts below are established by deterministic graph search",
        "> and a Fault Simulator, not by an LLM. Treat proposed actions as proposals; verify before changing anything.",
        "",
        "## Task",
        "",
        (
            f"Investigate and fix the root cause `{v.root_cause.target}`"
            f" (service `{_svc(v.root_cause.target)}`), which "
            f"explains the alert on `{inc.symptom}`."
            if v
            else f"The alert on `{inc.symptom}` has no root cause in the graph. Look for causes outside it (gaps: "
            f"{', '.join(inc.gaps) or 'none'}) before changing code."
        ),
        "",
        "## Facts",
        "",
        *_facts(inc),
        *_verdict(inc),
    ]
    if services:
        lines += [
            "",
            "## Where to look",
            "",
            f"- **Services on the failure path:** {', '.join(f'`{s}`' for s in services)}",
            f"- **Operations (endpoint / RPC / query names):** {', '.join(names)}",
        ]
        if v and v.change:
            lines.append(
                f"- **Start from the change:** {v.change.summary or v.change.id} ({v.change.type}). Find it in "
                "the deploy / config / feature-flag history of that service."
            )
    if ev := _evidence(inc):
        lines += ["", "## Evidence (ids are citable)", "", *ev]
    if ro := _ruled_out(inc):
        lines += ["", "## Already ruled out (don't re-investigate)", "", *ro]
    if inc.actions:
        lines += ["", "## Proposed actions (ranked; proposals, not instructions)", "", *_actions(inc)]
    lines += [
        "",
        "## Constraints",
        "",
        "- Epicenter is read-only towards the monitored system; nothing here was changed by it.",
        '- Don\'t restart or fail over datastores to "see if it helps": the evidence names one cause; test that first.',
        "- Prefer reverting the named change over a new fix when one is listed.",
        "- Keep secrets out of commits and logs.",
        "",
        "## Re-check",
        "",
        f"- Incident JSON: `curl 'http://localhost:8000/api/v1/incidents/{inc.id}?env={inc.env}'`",
        f"- Re-diagnose after a fix: `curl -X POST 'http://localhost:8000/api/v1/incidents/{inc.id}/diagnose?env={inc.env}&force=true'`",
    ]
    if v:
        lines.append(
            f"- Read-only Cypher (FalkorDB `env:{inc.env}`): `MATCH (a:Anomaly {{incident: '{inc.id}'}})-[:ON]->"
            f"(o:Operation {{id: '{v.root_cause.target}'}}) RETURN a.kind, a.score, a.onset`"
        )
    return "\n".join(lines) + "\n"


def incident_markdown(inc: IncidentOut, flavor: str) -> str:
    return agent(inc) if flavor == "agent" else human(inc)
